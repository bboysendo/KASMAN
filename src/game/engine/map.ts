export const W = MAZES[0].rows[0].length;
export const H = MAZES[0].rows.length;

export const PELLET = 1;
export const POWER = 2;

export const wrapX = (x: number) => ((x % W) + W) % W;

function buildMaze({ rows, tunnels }: (typeof MAZES)[number]) {
  const walls = new Uint8Array(W * H);
  rows.forEach((row, y) => [...row].forEach((c, x) => (walls[y * W + x] = c === "#" ? 1 : 0)));
  const isWall = (x: number, y: number) => y < 0 || y >= H || walls[y * W + wrapX(x)] === 1;
  const isOpen = (x: number, y: number) => !isWall(x, y);

  /** Tiles reachable from Pac-Man's start, in BFS order. Unreachable pockets never get pellets. */
  const reachable: Point[] = [];
  const seen = new Uint8Array(W * H);
  const queue: Point[] = [PAC_START];
  seen[PAC_START.y * W + PAC_START.x] = 1;
  while (queue.length) {
    const p = queue.shift()!;
    reachable.push(p);
    for (let d = 0; d < 4; d++) {
      const x = wrapX(p.x + DX[d]);
      const y = p.y + DY[d];
      if (isWall(x, y) || seen[y * W + x]) continue;
      seen[y * W + x] = 1;
      queue.push({ x, y });
    }
  }

  return {
    rows,
    tunnels,
    reachable: reachable as ReadonlyArray<Point>,
    isWall,
    isOpen,
    isTunnel: (x: number, y: number) => tunnels.includes(y) && (x < 5 || x > W - 6),
    createPellets() {
      const pellets = new Uint8Array(W * H);
      for (const { x, y } of reachable) {
        const c = rows[y][x];
        if (c === ".") pellets[y * W + x] = PELLET;
        else if (c === "o") pellets[y * W + x] = POWER;
      }
      return pellets;
    },
  };
}

export type Maze = ReturnType<typeof buildMaze>;
const BUILT = MAZES.map(buildMaze);
export const MAZE_COUNT = BUILT.length;
export const mazeFor = (level: number): Maze => BUILT[Math.min(Math.max(level, 1), MAZE_COUNT) - 1];
